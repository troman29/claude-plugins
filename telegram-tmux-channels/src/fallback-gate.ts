// Досылка ответа: пускать или нет.
//
// Хаб досылает финальный текст хода, когда агент забыл отписаться в Telegram. Метка ожидания
// взводится на КАЖДОЕ входящее — и это ломалось ровно на привычке дописывать пару строк, пока
// ход идёт: агент уже ответил, метка вставала заново, и в конце хода прилетал пересказ
// отправленного. Приходило «и одно, и другое».
//
// Знание живёт здесь, а не россыпью по hub.ts, потому что баг был не в условии, а в ЖИЗНЕННОМ
// ЦИКЛЕ: кто ставит, кто снимает и когда обнуляется. Такое проверяется тестом только целиком.
export class FallbackGate {
  private answered = new Set<string>()

  /** Агент сам что-то отправил в Telegram (reply/react/edit) в текущем ходе. */
  noteAnswered(key: string): void {
    this.answered.add(key)
  }

  /** Досылать ли финальный текст на конце хода. */
  shouldForward(key: string): boolean {
    return !this.answered.has(key)
  }

  /** Ход закрыт — следующий начинается с чистого листа. */
  endTurn(key: string): void {
    this.answered.delete(key)
  }
}
